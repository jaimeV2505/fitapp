import type { Equipment, MovementType, MuscleGroup } from "@/lib/db/schema/enums";

export interface BaseExercise {
  /** "base-<name>" */
  slug: string;
  name: string;
  /** Spanish name, shown when the app is in Spanish. */
  nameEs: string;
  primaryMuscle: MuscleGroup;
  secondaryMuscles: MuscleGroup[];
  movementType: MovementType;
  equipment: Equipment | null;
  defaultSets: number;
  defaultRepMin: number;
  defaultRepMax: number;
}

type Row = readonly [name: string, nameEs: string, equipment: Equipment, type: MovementType, secondary?: readonly MuscleGroup[]];

const B = "barbell";
const D = "dumbbell";
const M = "machine";
const C = "cable";
const W = "bodyweight";
const O = "other";
const COMPOUND = "compound";
const ISO = "isolation";

export function baseSlug(name: string): string {
  return `base-${name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")}`;
}

/** Sets and rep range that suit the muscle and the kind of movement. */
function defaultsFor(primary: MuscleGroup, type: MovementType): { sets: number; min: number; max: number } {
  if (primary === "calves" || primary === "forearms" || primary === "core") return { sets: 3, min: 12, max: 20 };
  return type === "compound" ? { sets: 3, min: 6, max: 10 } : { sets: 3, min: 10, max: 15 };
}

function section(primary: MuscleGroup, rows: readonly Row[]): BaseExercise[] {
  return rows.map(([name, nameEs, equipment, movementType, secondary]) => {
    const d = defaultsFor(primary, movementType);
    return {
      slug: baseSlug(name),
      name,
      nameEs,
      primaryMuscle: primary,
      secondaryMuscles: [...(secondary ?? [])],
      movementType,
      equipment,
      defaultSets: d.sets,
      defaultRepMin: d.min,
      defaultRepMax: d.max,
    };
  });
}

